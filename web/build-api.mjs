// Bundles the server into one file for Vercel: ../api/index.js. Libraries (firebase-admin) stay
// outside the bundle and are installed by Vercel from the package.json at the top of the repository.
import { build } from 'esbuild';

await build({
  entryPoints: ['server/vercel.ts'], outfile: '../api/index.js',
  bundle: true, platform: 'node', format: 'esm', target: 'node20', packages: 'external',
  banner: { js: '// Generated by web/build-api.mjs from web/server. Do not edit by hand.' },
});
console.log('api/index.js written');
